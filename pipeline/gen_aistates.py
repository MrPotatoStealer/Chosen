"""Generate QuakeC AI state tables from NBlood ai*.cpp AISTATE initializers.

usage: python -I gen_aistates.py <nblood_src_dir> <out_dir>

Writes:
  gen_aistates_decl.qc  - entity globals for every AISTATE + prototypes of referenced functions
  gen_aistates_init.qc  - aiInitStates(): allocates and fills every state entity

File-local (static) functions get a per-module prefix so they do not collide in QuakeC's
single namespace (e.g. aicult.cpp thinkChase -> cult_thinkChase). Hand-ported AI code uses
the same prefixed names.
"""
import os
import re
import sys

PREFIX = {
    'ai.cpp': '', 'aibat.cpp': 'bat_', 'aibeast.cpp': 'beast_', 'aiboneel.cpp': 'eel_', 'aiburn.cpp': 'burn_',
    'aicaleb.cpp': 'caleb_', 'aicerber.cpp': 'cerb_', 'aicult.cpp': 'cult_', 'aigarg.cpp': 'garg_',
    'aighost.cpp': 'ghost_', 'aigilbst.cpp': 'gill_', 'aihand.cpp': 'hand_', 'aihound.cpp': 'hound_',
    'aiinnoc.cpp': 'innoc_', 'aipod.cpp': 'pod_', 'airat.cpp': 'rat_', 'aispid.cpp': 'spid_',
    'aitchern.cpp': 'tcher_', 'aizomba.cpp': 'zomba_', 'aizombf.cpp': 'zombf_',
}

STATE_TYPES = {
    'kAiStateOther': -1, 'kAiStateIdle': 0, 'kAiStateGenIdle': 1, 'kAiStateMove': 2, 'kAiStateSearch': 3,
    'kAiStateChase': 4, 'kAiStateRecoil': 5, 'kAiStateAttack': 6, 'kAiStateKnockout': 7, 'kAiStateIdleSleep': 8,
}


def strip_comments(s):
    s = re.sub(r'/\*.*?\*/', ' ', s, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', s)


def main():
    src, out = sys.argv[1], sys.argv[2]
    states = []          # (name, type, seq, cbfunc, ticks, enter, move, think, next)
    funcs = set()
    seen = set()
    for fn, pre in PREFIX.items():
        with open(os.path.join(src, fn), encoding='latin1') as f:
            s = strip_comments(f.read())
        statics = set(re.findall(r'\bstatic\s+(?:void|int|bool|char)\s+(\w+)\s*\(', s))
        clients = dict(re.findall(r'(\w+)\s*=\s*seqRegisterClient\(\s*(\w+)\s*\)', s))

        def fname(n):
            n = n.strip()
            if n in ('NULL', '0', '-1', 'nullptr'):
                return None
            n = n.lstrip('&')
            if n in statics:
                return pre + n
            return n

        for m in re.finditer(r'AISTATE\s+(\w+)\s*=\s*\{([^}]*)\}\s*;', s):
            name = m.group(1)
            parts = [p.strip() for p in m.group(2).split(',')]
            if len(parts) != 8:
                print('skip', fn, name, parts)
                continue
            if name in seen:
                print('duplicate state', name, 'in', fn)
                continue
            seen.add(name)
            stype = STATE_TYPES.get(parts[0], None)
            if stype is None:
                stype = int(parts[0], 0)
            seq = int(parts[1], 0)
            cb = parts[2]
            cbf = None
            if cb not in ('-1',):
                cbf = clients.get(cb)
                if cbf is None:
                    print('unknown client', fn, name, cb)
                else:
                    cbf = pre + cbf if cbf in statics else cbf
            ticks = int(parts[3], 0)
            enter, move, think = fname(parts[4]), fname(parts[5]), fname(parts[6])
            nxt = parts[7].strip().lstrip('&')
            if nxt in ('NULL', '0'):
                nxt = None
            states.append((name, stype, seq, cbf, ticks, enter, move, think, nxt))
            for f_ in (cbf, enter, move, think):
                if f_:
                    funcs.add(f_)
    with open(os.path.join(out, 'gen_aistates_decl.qc'), 'w') as f:
        f.write('// generated by pipeline/gen_aistates.py -- do not edit\n')
        f.write('entity ' + ', '.join(s[0] for s in states) + ';\n')
        for fn_ in sorted(funcs):
            f.write('void(entity e) %s;\n' % fn_)
    with open(os.path.join(out, 'gen_aistates_init.qc'), 'w') as f:
        f.write('// generated by pipeline/gen_aistates.py -- do not edit\n')
        f.write('void() aiInitStates =\n{\n')
        for s in states:
            f.write('\t%s = aiAllocState("%s");\n' % (s[0], s[0]))
        for name, stype, seq, cbf, ticks, enter, move, think, nxt in states:
            f.write('\taiSetState(%s, %d, %d, %d);\n' % (name, stype, seq, ticks))
            if cbf:
                f.write('\t%s.st_callback = 1; %s.st_seqcb = %s;\n' % (name, name, cbf))
            if enter:
                f.write('\t%s.st_enter = %s;\n' % (name, enter))
            if move:
                f.write('\t%s.st_move = %s;\n' % (name, move))
            if think:
                f.write('\t%s.st_think = %s;\n' % (name, think))
            if nxt:
                f.write('\t%s.st_next = %s;\n' % (name, nxt))
        f.write('};\n')
    print('states', len(states), 'functions', len(funcs))


if __name__ == '__main__':
    main()
