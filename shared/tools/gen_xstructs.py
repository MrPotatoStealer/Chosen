"""Writes shared/Chosen.Blood/Map/XStructs.cs from pipeline/blood_map.py's field tables (NBlood db.h's XSECTOR, XWALL,
XSPRITE bit layouts): one class each with Read and Write, so the C# reader, the C# writer and the Python reader share one
description of the bits. Run after changing the tables: python -I shared/tools/gen_xstructs.py"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
import blood_map  # noqa: E402

OUT = os.path.join(ROOT, 'shared', 'Chosen.Blood', 'Map', 'XStructs.cs')


def cs_name(n):
    return n[0].upper() + n[1:]


def spec(s):
    return (int(s[1:]), True) if isinstance(s, str) else (s, False)


def one(cls, fields, file_size, what):
    names = [cs_name(n) for n, _ in fields]
    bits = sum(spec(s)[0] for _, s in fields)
    out = [f'/// <summary>{what} ({bits} bits of fields; the stored record is {file_size} bytes in Blood 1.21 maps,',
           '/// its size in the map header: Raw keeps it whole, so bits no field names survive a round trip).</summary>',
           f'public sealed class {cls}', '{',
           '    public int ' + ', '.join(names) + ';', '',
           '    /// <summary>The record as stored (its size from the map), the base Write writes the fields over.</summary>',
           '    public byte[] Raw;', '',
           f'    public const int FieldBits = {bits};',
           f'    /// <summary>The size of the whole record: a map may store it smaller (zero-filled), never larger.</summary>',
           f'    public const int FullSize = {file_size};', '',
           f'    /// <summary>The record at at, stored in size bytes: NBlood accepts a size up to the full {file_size} (the rest',
           '    /// reads as zeros), so the fields come from a zero-padded copy.</summary>',
           f'    public static {cls} Read(byte[] d, int at, int size)', '    {',
           f'        var full = new byte[System.Math.Max(size, {file_size})];',
           '        System.Array.Copy(d, at, full, 0, System.Math.Min(size, d.Length - at));',
           '        var r = new BitReader(full, 0);',
           f'        var x = new {cls}', '        {']
    for (n, s), cn in zip(fields, names):
        w, signed = spec(s)
        out.append(f'            {cn} = r.{"S" if signed else "U"}({w}),')
    out += ['        };',
            '        x.Raw = new byte[size];',
            '        System.Array.Copy(d, at, x.Raw, 0, System.Math.Min(size, d.Length - at));',
            '        return x;', '    }', '',
            f'    /// <summary>The record into dst at at, Size bytes: Raw (zeros for a new one, {file_size} bytes) with the fields',
            '    /// written over it (in a full-size scratch, so a record stored smaller keeps only its own bytes).</summary>',
            '    public void Write(byte[] dst, int at)', '    {',
            f'        int size = Raw?.Length ?? {file_size};',
            f'        var full = new byte[System.Math.Max(size, {file_size})];',
            '        if (Raw != null)',
            '            System.Array.Copy(Raw, full, size);',
            '        var w = new BitWriter(full, 0);']
    for (n, s), cn in zip(fields, names):
        width, _ = spec(s)
        out.append(f'        w.W({width}, {cn});')
    out += ['        System.Array.Copy(full, 0, dst, at, size);', '    }', '',
            f'    public int Size => Raw?.Length ?? {file_size};', '}', '']
    return out


def main():
    lines = ['// Chosen Blood module (GPL v2): the x-structure bit layouts of NBlood db.h (via pipeline/blood_map.py).',
             '// Generated by shared/tools/gen_xstructs.py from pipeline/blood_map.py\'s field tables: do not edit.',
             'namespace Chosen.Shared.Blood.Map;', '']
    lines += one('XSector', blood_map.XSECTOR_FIELDS, 60, "A sector's x-structure (XSECTOR)")
    lines += one('XWall', blood_map.XWALL_FIELDS, 24, "A wall's x-structure (XWALL)")
    lines += one('XSprite', blood_map.XSPRITE_FIELDS, 56, "A sprite's x-structure (XSPRITE)")
    lines += ['/// <summary>Bits from a byte array, lowest bit first (the x-structures\' bit fields).</summary>',
              'public struct BitReader', '{', '    readonly byte[] _d;', '    int _pos;', '',
              '    public BitReader(byte[] d, int at)', '    {', '        _d = d;', '        _pos = at * 8;', '    }', '',
              '    public int U(int n)', '    {', '        long v = 0;',
              '        for (int i = 0; i < n; i++, _pos++)',
              '            v |= (long)((_d[_pos >> 3] >> (_pos & 7)) & 1) << i;',
              '        return (int)v;', '    }', '',
              '    public int S(int n)', '    {', '        long v = (uint)U(n);',
              '        if (n < 32 && (v & (1L << (n - 1))) != 0)', '            v -= 1L << n;',
              '        return (int)v;', '    }', '}', '',
              '/// <summary>Bits into a byte array, lowest bit first: the mirror of BitReader (a value\'s low n bits).</summary>',
              'public struct BitWriter', '{', '    readonly byte[] _d;', '    int _pos;', '',
              '    public BitWriter(byte[] d, int at)', '    {', '        _d = d;', '        _pos = at * 8;', '    }', '',
              '    public void W(int n, int v)', '    {',
              '        for (int i = 0; i < n; i++, _pos++)', '        {',
              '            int bit = (int)(((long)v >> i) & 1);',
              '            int b = _pos >> 3, m = 1 << (_pos & 7);',
              '            _d[b] = (byte)(bit != 0 ? _d[b] | m : _d[b] & ~m);', '        }', '    }', '}', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote', OUT)


main()
